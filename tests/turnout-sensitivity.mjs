import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {turnoutShareBounds,turnoutScenario,turnoutOverview,historicalTurnout} from '../site/turnout-sensitivity.mjs';
import {turnoutPage} from '../site/turnout-ui.mjs';
const source=JSON.parse(readFileSync(new URL('../data/turnout-history-2018-2022.json',import.meta.url),'utf8'));
const historical=historicalTurnout(source);
assert.equal(historical.rows.length,22);
assert.deepEqual(historical.totals['2018'],{eligible:19102502,cast:12791449});
assert.deepEqual(historical.totals['2022'],{eligible:19181901,cast:11695610});
const taipei=historical.rows.find(x=>x.county==='台北市');
assert.equal(taipei.years['2022'].eligible,2026769);
assert.equal(taipei.years['2022'].cast,1372179);
assert.ok(Math.abs(taipei.years['2018'].rate-.6597)<.00005);
const chia=historical.rows.find(x=>x.county==='嘉義市');
assert.match(chia.special_note,/12月18日/);
assert.ok(Math.abs(historical.rows.reduce((s,r)=>s+r.years['2022'].cast,0)-11695610)<1);

const t0=.6;
const inc=turnoutShareBounds(.6,t0,5);
assert.ok(Math.abs(inc.lower-.36/.65)<1e-12);
assert.ok(Math.abs(inc.upper-.41/.65)<1e-12);
assert.equal(inc.proportional,.6);
const dec=turnoutShareBounds(.6,t0,-5);
assert.ok(Math.abs(dec.lower-.31/.55)<1e-12);
assert.ok(Math.abs(dec.upper-.36/.55)<1e-12);
assert.throws(()=>turnoutShareBounds(.6,t0,-80),/超出/);
const draws=Array.from({length:200},(_,i)=>i<100?[600000,400000]:[510000,490000]);
const model={counties:[{name:'台北市',race_id:'sample',
 candidates:[{name:'候選甲',candidate_id:'a'},{name:'候選乙',candidate_id:'b'}],draws}]};
const baseline=turnoutScenario(model,source,{county:'台北市',deltaPp:0});
assert.equal(baseline.robust_draws,200);
assert.equal(baseline.scenario_change_ballots,0);
const higher=turnoutScenario(model,source,{county:'台北市',deltaPp:5});
assert.equal(higher.robust_draws,100);
assert.equal(higher.robustness_share,.5);
assert.equal(higher.scenario_change_ballots,Math.round(2026769*.05));
assert.equal(higher.official_model_unchanged,true);
assert.equal(higher.candidates[0].model_valid_vote_share,.555);
const lower=turnoutScenario(model,source,{county:'台北市',deltaPp:-5});
assert.equal(lower.robust_draws,100);
assert.ok(higher.candidates[0].upper>higher.candidates[0].lower);
assert.ok(lower.candidates[0].upper>lower.candidates[0].lower);
assert.equal(model.counties[0].draws[0][0],600000);
assert.throws(()=>turnoutScenario(model,source,{county:'台北市',deltaPp:7}),/只接受/);
const corrupt=structuredClone(source);corrupt.records[0].years['2022'].cast+=10;
assert.throws(()=>historicalTurnout(corrupt),/不一致/);
const missing=turnoutPage(model,null,'台北市',5);
assert.match(missing,/無法核驗/);
const html=turnoutPage(model,source,'台北市',5);
assert.match(html,/2022實際投票率/);
assert.match(html,/101,338/);
assert.match(html,/選舉人數作分母/);
assert.match(html,/數學範圍/);
assert.match(html,/資料未通過核驗：/, '22 county model inputs must fail closed when missing');
